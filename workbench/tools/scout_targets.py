REJECT_PATTERNS = [
    r"do(?:es)?\s+not\s+accept\s+unsolicited\s+pull\s+requests",
    r"do\s+not\s+accept\s+pull\s+requests\s+from\s+non-?collaborators",
    r"we\s+do\s+not\s+accept\s+pull\s+requests",
    r"pull\s+requests\s+(?:are|will\s+be)\s+not\s+accepted",
]
AI_BAN_PATTERNS = [
    r"must\s+not\s+include\s+content\s+generated\s+by\s+large\s+language\s+models",
    r"(?:no|ban|forbid(?:den)?)\s+(?:ai|llm)[-\s](?:generated|assisted)",
    r"(?:ai|llm)[-\s]generated\s+(?:code|content|prs?|pull\s+requests?).{0,40}(?:not\s+allowed|forbidden|prohibited)",
]
GATE_PATTERNS = [
    (r"need\s+to\s+be\s+assigned|must\s+be\s+assigned|assigned\s+to\s+(?:an?\s+)?issue", "需先被指派"),
    (r"rfc[-\s]approved|requires?\s+(?:an?\s+)?rfc", "需 RFC"),
    (r"\bCLA\b|contributor\s+license\s+agreement", "需 CLA"),
    # ruyi 的真实门槛是 DCO sign-off（不是 CLA）；首版只认 CLA 曾把它误判成 GATED。
    (r"\bDCO\b|developer\s+certificate\s+of\s+origin|signed-off-by|sign-?off\s+(?:your\s+)?commits?",
     "需 DCO sign-off"),
    (r"please\s+ask\s+first|open\s+one\s+before\s+working|discuss\s+non-?trivial\s+changes", "需先开 issue/先问"),
]
WELCOME_PATTERNS = [
    r"(?:any\s+)?contributions?(?:\s+to\s+the\s+\w+)?\s+(?:are\s+|is\s+)?(?:warmly\s+|very\s+|always\s+)?welcome",
    r"pull\s+requests?\s+(?:are|is)\s+welcome",
    r"we\s+(?:warmly\s+)?welcome\s+(?:your\s+)?(?:contributions?|pull\s+requests?)",
]


def classify_policy(text: str | None) -> tuple[str, str]:
    """返回 (policy, 说明)。text=None 表示没找到 CONTRIBUTING 文件。"""
    if text is None:
        return "NONE", "无 CONTRIBUTING 文件（不排除，但政策未知）"
    low = text.lower()
    for pat in REJECT_PATTERNS:
        if re.search(pat, low):
            return "REJECT", "明确拒收外部 PR"
    for pat in AI_BAN_PATTERNS:
        if re.search(pat, low):
            return "AI_BAN", "禁止 AI/LLM 生成的内容（PR/issue/comment 均含）"
    # 11-04 合规复核修正：openai-agents-python 的 "Open an issue before preparing a
    # listing change" 只约束「集成列表变更」，不是代码 PR 的前置门槛。
    # 把 listing-change 句子剔除后再判 GATED，避免正则误报（条款命中须回读作用域）。
    scoped = re.sub(r"[^\n]*listing change[^\n]*", "", low)
    gates = [label for pat, label in GATE_PATTERNS if re.search(pat, scoped)]
    if gates:
        return "GATED", "、".join(dict.fromkeys(gates))
    for pat in WELCOME_PATTERNS:
        if re.search(pat, low):
            return "WELCOME", "明确欢迎外部贡献"
    return "UNKNOWN", "有政策文件但未识别到明确条款（需人工读原文）"


def is_policy_file(path: str) -> bool:
    """政策文件筛选（纯函数，可离线 self-test）。

    anemoi-utils 的 `CONTRIBUTORS.md` 是贡献者名单，含 "contribut" 但不是政策
    → 必须排除，否则会把「无政策」误判成 UNKNOWN。
    """
    if not re.search(r"(contribut|code.?of.?conduct|conduct)", path, re.I):
        return False
    if re.search(r"contributors?\.", path, re.I):
        return False
    return True


def read_contributing(repo: str) -> tuple[str | None, str]:
    """优先用 Git Trees API 递归列出政策文件，再回退到固定路径猜测。

    11-04 合规复核教训：只按固定路径 GET 时，3 个仓库报「未找到」，
    无法区分「路径猜错」与「真的没有」；且 reader 的政策是 `.rst`、tinycss2 是
    `docs/contribute.rst`，固定清单都可能漏。递归 trees + truncated=false 才可信。
    """
    m = api(f"/repos/{repo}")
    branch = m.get("default_branch", "main") if isinstance(m, dict) else "main"
    tree = api(f"/repos/{repo}/git/trees/{urllib.parse.quote(branch)}?recursive=1")
    if isinstance(tree, dict) and "tree" in tree and not tree.get("truncated"):
        names = [x["path"] for x in tree["tree"] if is_policy_file(x["path"])]
        # 合并所有政策文件：ruyi 的 CLA 条款在 .github/CONTRIBUTING.md，
        # 只取第一个（CONTRIBUTING.md 中文版）会漏掉 → 必须拼接后整体判定。
        chunks, used = [], []
        for p in sorted(names, key=lambda q: (q.count("/"), q))[:8]:
            d = api(f"/repos/{repo}/contents/{urllib.parse.quote(p)}?ref={branch}", quiet404=True)
            if isinstance(d, dict) and d.get("encoding") == "base64":
                try:
                    chunks.append(base64.b64decode(d["content"]).decode("utf-8", "replace"))
                    used.append(p)
                except Exception:
                    continue
        if chunks:
            return "\n".join(chunks), "+".join(used[:3])
    for p in CONTRIB_PATHS:
        d = api(f"/repos/{repo}/contents/{p}", quiet404=True)
        if isinstance(d, dict) and d.get("encoding") == "base64":
            try:
                return base64.b64decode(d["content"]).decode("utf-8", "replace"), p
            except Exception:
                return None, p
    return None, "-"


@dataclass
class Result:
    repo: str
    stars: int
    open_pr: int
    pushed: str
    policy: str
    policy_note: str
    contrib_path: str
    archived: bool
    err: str = ""

    @property
    def s1(self) -> bool:
        return 0 <= self.open_pr <= CROWD_LIMIT

    @property
    def s2(self) -> bool:
        return self.policy in ("WELCOME", "UNKNOWN", "NONE")

    @property
    def stale_days(self) -> int | None:
        if len(self.pushed) != 10:
            return None
        import datetime
        try:
            d = datetime.date.fromisoformat(self.pushed)
            return (datetime.date.today() - d).days
        except ValueError:
            return None

    @property
    def verdict(self) -> str:
        if self.err:
            return "ERR"
        if self.policy in ("REJECT", "AI_BAN"):
            return "EXCLUDE"
        if self.policy == "GATED":
            return "GATED"
        if self.archived:
            return "EXCLUDE"
        age = self.stale_days
        if age is not None and age > STALE_DAYS:
            return "STALLED"
        if self.s1 and self.s2:
            return "CANDIDATE"
        return "CROWDED"


def inspect(repo: str) -> Result:
    # 单库失败必须被隔离：ThreadPoolExecutor.map 里一个未捕获异常会中断整批。
    try:
        m = api(f"/repos/{repo}")
        if not isinstance(m, dict) or "_err" in m:
            return Result(repo, 0, -1, "-", "NONE", "-", "-", False, str(m)[:60])
        n = count_open_prs(repo)
        text, cpath = read_contributing(repo)
        policy, note = classify_policy(text)
        return Result(repo, m.get("stargazers_count", 0), n,
                      (m.get("pushed_at") or "")[:10], policy, note, cpath,
                      bool(m.get("archived")))
    except Exception as e:  # noqa: BLE001
        return Result(repo, 0, -1, "-", "NONE", "-", "-", False,
                      f"{type(e).__name__}: {str(e)[:50]}")


