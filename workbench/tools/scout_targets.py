def _headers() -> dict:
    tok = os.environ.get("GITHUB_TOKEN") or os.environ.get("GH_TOKEN") or ""
    return {
        "Authorization": "Bearer " + tok,
        "Accept": "application/vnd.github+json",
        "X-GitHub-Api-Version": "2022-11-28",
        "User-Agent": "target-scout",
    }


def api(path: str, quiet404: bool = False, with_headers: bool = False):
    req = urllib.request.Request(API + path, headers=_headers())
    try:
        with urllib.request.urlopen(req, timeout=10) as r:
            data = json.load(r)
            return (data, dict(r.headers)) if with_headers else data
    except urllib.error.HTTPError as e:
        if e.code == 404 and quiet404:
            return (None, {}) if with_headers else None
        return {"_err": f"HTTP {e.code}"}
    except (http.client.IncompleteRead, urllib.error.URLError, OSError) as e:
        # 大仓拉 per_page=100 的完整 PR 对象会截断连接（实测 888KB IncompleteRead）。
        return {"_err": type(e).__name__}


def count_open_prs(repo: str) -> int:
    """用 per_page=1 + Link 头的 rel="last" 数 open PR，避免下载全部 PR 对象。

    GitHub 大仓 `/pulls?per_page=100` 响应体近 1MB，代理下会 IncompleteRead。
    per_page=1 只取一个对象，总数从 Link 头解析；单页时直接数元素。
    """
    got = api(f"/repos/{repo}/pulls?state=open&per_page=1", with_headers=True)
    if isinstance(got, dict) and "_err" in got:
        return -1
    data, headers = got
    link = headers.get("Link") or headers.get("link") or ""
    m = re.search(r'[?&]page=(\d+)>;\s*rel="last"', link)
    if m:
        return int(m.group(1))
    return len(data) if isinstance(data, list) else -1


